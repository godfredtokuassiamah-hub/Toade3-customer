// Builds supabase/migrations/0008_catalog_seed.sql from the CURRENT mock
// data, so the database matches the app exactly (same ids as legacy_id).
// Pure and deterministic. Not imported by the app: used by
// scripts/generate-catalog-seed.js (writes the file) and seed-drift-test.ts
// (fails when the mock data changed but the SQL wasn't regenerated).
import { CATEGORIES, ITEMS, VENDORS } from "../../../data/mock/catalog";
import { getCompareAtMinor, getItemDescription, getOptionGroups } from "../../../data/mock/itemOptions";
import { STORES } from "../../../data/mock/stores";
import { getVendorLocation } from "../../../data/mock/vendorLocations";

function q(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function num(value: number | null | undefined): string {
  return value == null ? "null" : String(value);
}

function bool(value: boolean): string {
  return value ? "true" : "false";
}

function textArray(values: readonly string[] | undefined): string {
  if (!values || values.length === 0) return "'{}'::text[]";
  return `array[${values.map(q).join(", ")}]::text[]`;
}

function rows(list: string[]): string {
  return list.map((r) => `  (${r})`).join(",\n");
}

export type SeedCounts = {
  categories: number;
  vendors: number;
  stores: number;
  products: number;
  optionGroups: number;
  options: number;
};

export function seedCounts(): SeedCounts {
  let optionGroups = 0;
  let options = 0;
  for (const item of ITEMS) {
    const groups = getOptionGroups(item.item_id, item.category_ids);
    optionGroups += groups.length;
    for (const g of groups) options += g.options.length;
  }
  return {
    categories: CATEGORIES.length,
    vendors: VENDORS.length,
    stores: STORES.length,
    products: ITEMS.length,
    optionGroups,
    options,
  };
}

export function buildSeedSql(): string {
  const counts = seedCounts();
  const out: string[] = [];

  out.push(
    `-- 0008_catalog_seed.sql: GENERATED by scripts/generate-catalog-seed.js from
-- src/data/mock/{catalog,stores,itemOptions,vendorLocations}.ts. DO NOT EDIT BY
-- HAND: change the mock data, run \`node scripts/generate-catalog-seed.js\`.
-- seed-drift-test.ts fails when this file is out of date.
--
-- Run order: last, after 0004-0007 (see supabase/SETUP.md). Re-runnable:
-- every insert upserts on its natural key (legacy_id / id).
-- UNEXECUTED: written without database access; statically reviewed only.
--
-- Rows: ${counts.categories} categories, ${counts.vendors} catalog vendors, ${counts.stores} directory stores,
-- ${counts.products} products, ${counts.optionGroups} option groups, ${counts.options} options.
-- Image paths stay null: the app keeps its dummy image mapping until the
-- vendor app uploads real photos.
`,
  );

  // Categories.
  out.push(`-- 1. Categories
insert into public.categories (id, label, scope, icon, sort) values
${rows(CATEGORIES.map((c, i) => `${q(c.id)}, ${q(c.label)}, ${q(c.scope)}, ${q(c.icon)}, ${i}`))}
on conflict (id) do update set
  label = excluded.label, scope = excluded.scope, icon = excluded.icon, sort = excluded.sort;
`);

  // Catalog vendors.
  out.push(`-- 2. Catalog vendors (own the products; not listed in the Stores tab)
insert into public.vendors (
  legacy_id, slug, name, category, listed, lat, lng, prep_min, prep_max,
  is_open, opening_hours, paused, published) values
${rows(
  VENDORS.map((v) => {
    const loc = getVendorLocation(v.vendor_id);
    const hours = JSON.stringify({ open: v.hours.open, close: v.hours.close });
    return [
      q(v.vendor_id),
      q(v.vendor_id),
      q(v.name),
      "null",
      "false",
      num(loc.latitude),
      num(loc.longitude),
      num(loc.prepMins[0]),
      num(loc.prepMins[1]),
      "true",
      `${q(hours)}::jsonb`,
      bool(v.paused),
      "true",
    ].join(", ");
  }),
)}
on conflict (legacy_id) do update set
  slug = excluded.slug, name = excluded.name, category = excluded.category,
  listed = excluded.listed, lat = excluded.lat, lng = excluded.lng,
  prep_min = excluded.prep_min, prep_max = excluded.prep_max,
  is_open = excluded.is_open, opening_hours = excluded.opening_hours,
  paused = excluded.paused, published = excluded.published;
`);

  // Directory stores.
  out.push(`-- 3. Stores-tab directory entries (menu = menu_vendor_id's products)
insert into public.vendors (
  legacy_id, slug, name, category, listed, menu_vendor_id, lat, lng,
  prep_min, prep_max, is_open, opening_hours, paused, published) values
${rows(
  STORES.map((s) =>
    [
      q(s.id),
      q(s.id),
      q(s.name),
      q(s.category),
      "true",
      s.vendorId
        ? `(select v.id from public.vendors v where v.legacy_id = ${q(s.vendorId)})`
        : "null",
      num(s.latitude),
      num(s.longitude),
      num(s.prepMins[0]),
      num(s.prepMins[1]),
      bool(s.open),
      "null",
      "false",
      "true",
    ].join(", "),
  ),
)}
on conflict (legacy_id) do update set
  slug = excluded.slug, name = excluded.name, category = excluded.category,
  listed = excluded.listed, menu_vendor_id = excluded.menu_vendor_id,
  lat = excluded.lat, lng = excluded.lng,
  prep_min = excluded.prep_min, prep_max = excluded.prep_max,
  is_open = excluded.is_open, opening_hours = excluded.opening_hours,
  paused = excluded.paused, published = excluded.published;
`);

  // Products.
  out.push(`-- 4. Products (prices in integer pesewas)
insert into public.products (
  legacy_id, vendor_id, name, aliases, description, scope, price_minor,
  compare_at_minor, weight_g, stock, disabled, published, image_path, eta_mins,
  popular, discount_percent) values
${rows(
  ITEMS.map((i) =>
    [
      q(i.item_id),
      `(select v.id from public.vendors v where v.legacy_id = ${q(i.vendor_id)})`,
      q(i.name),
      textArray(i.aliases),
      q(getItemDescription(i.item_id, i.category_ids)),
      q(i.scope),
      num(i.price_minor),
      num(getCompareAtMinor(i.item_id, i.price_minor)),
      num(i.weight_g),
      num(i.stock),
      bool(i.disabled),
      bool(i.published),
      "null",
      num(i.eta_mins),
      bool(i.popular === true),
      num(i.discountPercent ?? null),
    ].join(", "),
  ),
)}
on conflict (legacy_id) do update set
  vendor_id = excluded.vendor_id, name = excluded.name, aliases = excluded.aliases,
  description = excluded.description, scope = excluded.scope,
  price_minor = excluded.price_minor, compare_at_minor = excluded.compare_at_minor,
  weight_g = excluded.weight_g, stock = excluded.stock, disabled = excluded.disabled,
  published = excluded.published, eta_mins = excluded.eta_mins,
  popular = excluded.popular, discount_percent = excluded.discount_percent;
`);

  // Category membership.
  const memberships: string[] = [];
  for (const i of ITEMS) for (const c of i.category_ids) memberships.push(`${q(i.item_id)}, ${q(c)}`);
  out.push(`-- 5. Product categories
insert into public.product_categories (product_id, category_id)
select p.id, m.category_id
from (values
${rows(memberships)}
) as m (product_legacy_id, category_id)
join public.products p on p.legacy_id = m.product_legacy_id
on conflict (product_id, category_id) do nothing;
`);

  // Option groups + options.
  const groupRows: string[] = [];
  const optionRows: string[] = [];
  for (const i of ITEMS) {
    getOptionGroups(i.item_id, i.category_ids).forEach((g, gi) => {
      groupRows.push(
        [q(i.item_id), q(g.id), q(g.title), bool(g.required), num(g.min), num(g.max), num(gi)].join(", "),
      );
      g.options.forEach((o, oi) => {
        optionRows.push(
          [q(i.item_id), q(g.id), q(o.id), q(o.label), num(o.priceMinor), num(oi)].join(", "),
        );
      });
    });
  }
  out.push(`-- 6. Option groups (one row per product + group)
insert into public.option_groups (product_id, legacy_id, title, required, min_select, max_select, sort)
select p.id, g.legacy_id, g.title, g.required, g.min_select, g.max_select, g.sort
from (values
${rows(groupRows)}
) as g (product_legacy_id, legacy_id, title, required, min_select, max_select, sort)
join public.products p on p.legacy_id = g.product_legacy_id
on conflict (product_id, legacy_id) do update set
  title = excluded.title, required = excluded.required,
  min_select = excluded.min_select, max_select = excluded.max_select, sort = excluded.sort;
`);

  out.push(`-- 7. Options
insert into public.options (group_id, legacy_id, label, price_minor, sort)
select g.id, o.legacy_id, o.label, o.price_minor, o.sort
from (values
${rows(optionRows)}
) as o (product_legacy_id, group_legacy_id, legacy_id, label, price_minor, sort)
join public.products p on p.legacy_id = o.product_legacy_id
join public.option_groups g on g.product_id = p.id and g.legacy_id = o.group_legacy_id
on conflict (group_id, legacy_id) do update set
  label = excluded.label, price_minor = excluded.price_minor, sort = excluded.sort;
`);

  return out.join("\n");
}
